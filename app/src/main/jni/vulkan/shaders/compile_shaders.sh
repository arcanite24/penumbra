#!/bin/sh
# Regenerates shaders_spv.h from the GLSL sources. Run after editing a shader.
# Uses the glslc that ships with the NDK (ndk/<version>/shader-tools/<host>/glslc).
set -e

cd "$(dirname "$0")"

GLSLC="${GLSLC:-glslc}"
OUT=../shaders_spv.h

# Array name, source, extra glslc arguments
compile() {
    echo "static const uint32_t $1[] ="
    "$GLSLC" -O --target-env=vulkan1.1 -mfmt=c $3 -o - "$2"
    echo ";"
    echo
}

{
    echo "// Generated by shaders/compile_shaders.sh from video.vert, video.frag, video_planar.frag, keep_busy.comp,"
    echo "// easu.frag, rcas.frag and sgsr.frag. Do not edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo
    compile kVideoVertSpv video.vert
    compile kVideoFragSpv video.frag
    compile kVideoPlanarFragSpv video_planar.frag
    compile kKeepBusyCompSpv keep_busy.comp
    # Upscaling (RendererConfig::upscaler): FSR 1 is EASU then RCAS, SGSR is one pass. EASU and
    # SGSR read the video, so each has a MediaCodec variant and a PyroWave one (-DPLANAR).
    compile kEasuFragSpv easu.frag
    compile kEasuPlanarFragSpv easu.frag -DPLANAR
    compile kRcasFragSpv rcas.frag
    compile kSgsrFragSpv sgsr.frag
    compile kSgsrPlanarFragSpv sgsr.frag -DPLANAR
} > "$OUT"

echo "Wrote $OUT"
